[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$repositoryRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot "../.."))

function Assert-Condition {
	param(
		[Parameter(Mandatory)][bool]$Condition,
		[Parameter(Mandatory)][string]$Message
	)
	if (-not $Condition) { throw $Message }
}

$launcherPath = Join-Path $repositoryRoot "build/showcase/Invoke-InvestorDemo.ps1"
$entryPointPath = Join-Path $repositoryRoot "build/showcase/Start-rtaime-Showcase.cmd"
$packagedTestPath = Join-Path $repositoryRoot "build/showcase/Test-PackagedInvestorDemo.ps1"
$documentationPath = Join-Path $repositoryRoot "docs/InvestorDemoScenario.md"
$bundlePolicyPath = Join-Path $repositoryRoot "build/release/offline-bundle-policy.json"
$workflowPath = Join-Path $repositoryRoot ".github/workflows/required-gates.yml"
$appCodePath = Join-Path $repositoryRoot "src/Hosts/rtaime.Operator/App.xaml.cs"

foreach ($path in @($launcherPath, $entryPointPath, $packagedTestPath, $documentationPath, $bundlePolicyPath, $workflowPath, $appCodePath)) {
	Assert-Condition (Test-Path -LiteralPath $path -PathType Leaf) "Required investor-demo artifact is missing: '$path'."
}

$launcher = Get-Content -LiteralPath $launcherPath -Raw
$entryPoint = Get-Content -LiteralPath $entryPointPath -Raw
$packagedTest = Get-Content -LiteralPath $packagedTestPath -Raw
$documentation = Get-Content -LiteralPath $documentationPath -Raw
$bundlePolicy = Get-Content -LiteralPath $bundlePolicyPath -Raw | ConvertFrom-Json
$workflow = Get-Content -LiteralPath $workflowPath -Raw
$appCode = Get-Content -LiteralPath $appCodePath -Raw

foreach ($artifact in @($launcher, $entryPoint, $packagedTest, $documentation)) {
	Assert-Condition ($artifact -match 'Copyright \(c\).*Dave Beusing') "Investor-demo text artifacts must retain the project copyright header."
	Assert-Condition ($artifact -notmatch '(?i)chatgpt|codex|agentic|generated by') "Investor-demo artifacts must not contain assistant/tool provenance."
}

foreach ($tool in @("build/showcase/Invoke-InvestorDemo.ps1", "build/showcase/Start-rtaime-Showcase.cmd")) {
	Assert-Condition (@($bundlePolicy.offlineTools) -contains $tool) "Offline release bundle does not carry required showcase tool '$tool'."
}

Assert-Condition ($entryPoint -match 'Invoke-InvestorDemo\.ps1') "One-click entry point must delegate to the governed showcase launcher."
Assert-Condition ($entryPoint -notmatch 'ControlHost|RuntimeHost|AIHost') "One-click entry point must not directly launch production hosts."
Assert-Condition ($launcher -match 'Invoke-ManagedHostLifecycle\.ps1') "Showcase launcher must reuse the managed host lifecycle controller."
Assert-Condition ($launcher -match 'rtaime\.Operator\.dll') "Showcase launcher must start the packaged Operator client."
Assert-Condition ($launcher -notmatch 'rtaime\.(ControlHost|RuntimeHost|AIHost)\.dll') "Showcase launcher must not duplicate child/service host supervision."
Assert-Condition ($launcher -match 'RTAIME_CONTROL_ENDPOINT' -and $launcher -match 'RTAIME_RUNTIME_ENDPOINT' -and $launcher -match 'RTAIME_MONITOR_ENDPOINT') "Operator must bind to the exact managed lifecycle endpoints."
Assert-Condition ($launcher -match 'HeadlessAcceptance' -and $launcher -match 'showcase-receipt-latest\.json') "Showcase launcher must provide deterministic packaged acceptance evidence."
Assert-Condition ($appCode -match '--headless-once' -and $appCode -match 'stopAfterFirstSuccess') "Operator must support bounded one-shot readiness qualification."
Assert-Condition ($packagedTest -match 'Install-OfflineRelease\.ps1' -and $packagedTest -match 'HeadlessAcceptance') "Packaged acceptance must execute from an installed release, not repository binaries."
Assert-Condition ($packagedTest -match 'Manual service start: NOT REQUIRED' -and $packagedTest -match 'Terminal configuration: NOT REQUIRED') "Packaged acceptance must assert the no-manual-bootstrap contract."

foreach ($requiredText in @(
	"Start-rtaime-Showcase.cmd",
	"Open Demo Production",
	"Timeline",
	"Cue",
	"Preview",
	"Program",
	"DISSOLVE",
	"Graphics",
	"Audio",
	"AI",
	"Recording",
	"Program Output",
	"Runtime Health",
	"No terminal",
	"No JSON",
	"No manually started services"
)) {
	Assert-Condition ($documentation -match [Regex]::Escape($requiredText)) "Investor demo documentation is missing '$requiredText'."
}

Assert-Condition ($workflow -match 'Test-InvestorDemoPolicy\.ps1') "Required Gates must execute investor-demo policy verification."
Assert-Condition ($workflow -match 'Test-PackagedInvestorDemo\.ps1') "Packaged E2E must qualify the installed investor-demo launcher."

Write-Host "Investor demo policy verification PASS"
Write-Host "One-click bootstrap: managed lifecycle + Operator"
Write-Host "Packaged acceptance: installed release + one-shot Operator readiness + graceful lifecycle stop"
Write-Host "Investor scenario: deterministic human demo sequence with explicit manual visual checks"
